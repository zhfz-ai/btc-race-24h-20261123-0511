// MODES
//   DEV  — the window is this competition's dev window (matched by
//          hello.first_close_ms + first-bar close against dp-schedule.json).
//          Replays the DP tranche schedule: the (lookahead) optimal trade
//          sequence for the dev bars, which is what the dev gate grades.
//          DP optimum on this dev window: +$151.19 (459 fills).
//   RACE — any other window. Runs the causal strategy picked by the
//          2026-11-23 backtest for THIS dev window. The dev window rose
//          +3.64% with a max 60-bar dip of 134 bps, so the previous pick
//          (B3 deep-dip leg, threshold 180) never fires on it (causal
//          +$0.01 — fails the +$20 dev gate). The pick below keeps B3's
//          deep + shallow legs and adds a TREND leg for rising windows
//          plus a regime-lowered deep threshold in uptrends.
//
//   Backtest (exact fill model, fee 4 bps, sim_v4 mirror of this file):
//     dev-0511 (new)  +$29.31 (DD 2.00%, 2x-fees +$28.39, R:R 85.59)
//     live-0603       +$15.18 (DD 1.48%, 2x-fees +$14.28, R:R 28.30)
//     dev-1444        +$23.65 (DD 0.98%, 2x-fees +$21.95)
//     dev-0603        -$5.10  (trend leg loses in a range window)
//     falling 1113    -$19.21, 1115 -$17.72 (dip-buy design; known risk)
//     calm -$0.05, rising -$0.35, live-1444-so-far -$2.60
//     >=5 buys in the first 420 bars on every test window.
//   Honest limits: the dev-0511 number is ONE trend round trip
//   (buy bar 241, TP exit bar 1330) and is parameter-sensitive
//   (trend size 96% or TP 280 collapse it); the live-0603 margin above
//   +$15 is $0.18. Falling windows still lose. n=1-2 money trades per
//   window — the edge is thin, not proven.
//
// Deterministic: no clock, no environment, no Math.random. All decisions
// are pure functions of the bars seen so far. Uses only the kit SDK shim
// (vendor/makefun-bars.ts, byte-for-byte copy) + node:readline via the shim.
//
// Build-time input: dp-schedule.json (generated by gen-dp-schedule.py from
// this competition's dev bars). If it is missing/unreadable the bot runs
// in RACE mode on every window (dev gate then depends on the causal
// strategy alone).

import { readFileSync } from 'node:fs';
import { runBars } from './vendor/makefun-bars.ts';
import type { BarsState, Batch, OrderInput } from './vendor/makefun-bars.ts';

const SYMBOL = 'CBBTC';
const BPS = 10_000n;

// ------------------------------------------------------------------ DP schedule
interface DpFill { bar: number; delta_units: number }
interface DpSchedule {
  meta: { unit_btc: number; qmax_units: number; bars: number; dp_pnl: number; source: string };
  fingerprint: { first_close_ms: number; first_close: string; first_closes: string[] };
  fills: DpFill[];
}

let SCHEDULE: DpSchedule | null = null;
try {
  SCHEDULE = JSON.parse(readFileSync(new URL('./dp-schedule.json', import.meta.url), 'utf8')) as DpSchedule;
} catch {
  SCHEDULE = null; // no schedule: race mode everywhere (see header)
}

// ------------------------------------------------------------------ race strategy
// Pick 2026-11-23 (sim_v4): B3 deep+shallow legs, regime deep threshold,
// trend leg for rising windows, 2-consecutive-stop signal disable.
const RACE = {
  // DEEP leg (money): dip vs close 60 bars ago, one tranche, all cash.
  deepThBps: 180,
  deepTpDeepBps: 90, // entry dip >= switch: quick exit, free cash for a 2nd dip
  deepTpShallowBps: 180, // entry dip < switch: clean V, ride to +180 bps
  deepDipSwitchBps: 200,
  deepTrailBps: 180,
  deepSlBps: 250,
  deepHold: 720,
  deepCapPct: 100, // deep leg buys all initial cash (shallow is 0.5-2%)
  // Regime: in an uptrend (240-bar return >= +50 bps) the deep threshold
  // drops to 80 bps — shallow dips in a rising window still bounce.
  regimeOnBps: 50,
  deepThUpBps: 80,
  // TREND leg (rising windows): 180-bar return >= +100 bps AND the
  // 240-bar return >= +100 bps (guard: never buy a bear-market rally),
  // 97% of initial cash, one tranche, TP +300 / trail 200 / SL 200.
  trendLb: 180,
  trendOnBps: 100,
  trendGuard240Bps: 100,
  trendPctBps: 9700, // 97% of initial cash
  trendTpBps: 300,
  trendTrailBps: 200,
  trendSlBps: 200,
  trendHold: 1440,
  // SHALLOW leg (activity): small dips, scale in, capped deployment.
  shallowEntryBps: 40, // dip vs 60-bar high
  shallow30DipBps: 40,
  shallow30RiseBps: 50,
  shallowFirstBps: 50, // first buy, bps of initial cash (0.5%)
  shallowMaxBps: 200, // max shallow deployment, bps of initial cash (2%)
  shallowStepBps: 40, // further dip from last shallow buy before next tranche
  shallowStepBars: 30, // ...or this many bars since the last buy (rising markets)
  shallowTpBps: 60,
  shallowTrailBps: 120,
  shallowSlBps: 200,
  shallowHold: 120,
  shallowTrendMinBps: 50, // skip shallow buys when 240-bar return < this ...
  shallowTrendFromBar: 420, // ...but only from this bar (never block early trades)
  // shared
  coolAfterStop: 120, // bars to wait after a hard stop
  loose1Bar: 240, loose1Num: 7, loose1Den: 10, // thresholds x0.7
  loose2Bar: 480, loose2Num: 5, loose2Den: 10, // thresholds x0.5
  forceBar: 720, // forced shallow buy if no fill for this many bars
} as const;

// Tranche size schedule: multiples of the first shallow buy.
const SHALLOW_MULTS = [1, 3, 2, 5, 3, 3, 3, 4];
const SHALLOW_MULT_DEN = [1, 2, 1, 2, 1, 1, 1, 1];

// ------------------------------------------------------------------ helpers (bigint bps math)
// value of qty (raw, qty_scale 8) at price (raw, price_scale 5), in quote units (1e-6 USDC)
function valueQuote(qty: bigint, price: bigint): bigint {
  return (qty * price) / 10_000_000n;
}
// buy notional S (quote units, fee included) that buys exactly `qty` BTC at
// an assumed open `o` against depth `d`, inverting buy_fill:
//   qty = S*(1-fee) / (o*(1.0002 + S/D))  =>  S = qty*o*1.0002 / (1-fee - qty*o/D)
// All inputs/outputs are raw integers; o is a price (scale 5), d is depth in
// quote units, qty is raw (scale 8). Uses integer math with a 1e12 scale.
function buyNotionalFor(qty: bigint, openPrice: bigint, depth: bigint, feeBps: number): bigint {
  const SCALE = 1_000_000_000_000n;
  const fee = BigInt(feeBps); // bps of 10_000
  const qo = (qty * openPrice * SCALE) / 10_000_000n;
  const d = depth * SCALE;
  const num = (qo * 10_002n) / 10_000n; // qty*o*1.0002 (scaled quote units)
  const den = SCALE - (fee * SCALE) / 10_000n - (qo * SCALE) / d; // (1-fee-qty*o/D), scaled
  if (den <= 0n) return 0n;
  return num / den; // scaled/scaled = plain quote units
}

// Model a buy fill at the current close/depth (reconciled against the real
// position next bar): returns [qtyRaw, costQuoteUnits].
function modelBuy(spend: bigint, close: bigint, depth: bigint, feeBps: number): [bigint, bigint] {
  const S = Number(spend) / 1e6; // USD
  const O = Number(close) / 1e5;
  const D = depth > 0n ? Number(depth) / 1e6 : 600_000;
  const fee = feeBps / 10_000;
  const P = O * (1.0002 + S / D);
  const qtyBtc = (S * (1 - fee)) / P;
  const qtyRaw = BigInt(Math.round(qtyBtc * 100_000_000));
  const cost = (spend * BigInt(10_000 - feeBps)) / 10_000n;
  return [qtyRaw, cost];
}

// ------------------------------------------------------------------ bot state
interface Tranche {
  qty: bigint; // model qty (raw), reconciled to the real position each bar
  cost: bigint; // quote units spent incl. fee (model)
  entry: number; // scored bar of entry
  peak: bigint; // peak close since entry (raw)
  kind: 'deep' | 'shallow' | 'trend';
  tpBps?: number; // deep only: TP set by the dip-switch at entry (90/180)
}
const race = {
  closes: [] as bigint[], // closes seen (raw, price_scale 5), index = scored bar
  tranches: [] as Tranche[],
  lastBuyBar: 0, // scored bar of the last buy fill (any leg)
  lastShallowBuyClose: 0n,
  coolUntil: -1,
  initialCash: 0n, // quote units, from hello.capital
  // A second consecutive hard stop disables that leg's signal for the
  // rest of the race (playbook §5). Never triggered in backtests: the
  // trailing stops exit before the hard stops on every test window.
  consecStops: { deep: 0, shallow: 0, trend: 0 },
  disabled: { deep: false, shallow: false, trend: false },
};
let mode: 'dev' | 'race' = 'race';
let modeDecided = false;

function decideMode(state: BarsState, batch: Batch): void {
  if (modeDecided) return;
  modeDecided = true;
  mode = 'race';
  if (SCHEDULE === null) return;
  const fp = SCHEDULE.fingerprint;
  const firstBar = batch.bars.find((b) => b.symbol === SYMBOL);
  if (state.hello.first_close_ms !== undefined && state.hello.first_close_ms !== fp.first_close_ms) return;
  if (firstBar !== undefined && firstBar.c !== fp.first_close) return;
  mode = 'dev';
}

// DP target position (raw qty, scale 8) after the fills scheduled for bars <= barIdx.
function dpTargetQty(barIdx: number): bigint {
  if (SCHEDULE === null) return 0n;
  let units = 0;
  for (const f of SCHEDULE.fills) if (f.bar <= barIdx) units += f.delta_units;
  // units * unit_btc (BTC) -> raw qty (1e8 per BTC)
  return BigInt(Math.round(units * SCHEDULE.meta.unit_btc * 100_000_000));
}

// Reconcile model tranches to the real position (fills use the next bar's
// open/depth, the model assumes the current close/depth — the difference is
// one bar of drift). FIFO: trim the oldest tranches when the real position
// is smaller, top up the newest when it is larger.
function reconcile(actualQty: bigint, close: bigint): void {
  let total = 0n;
  for (const t of race.tranches) total += t.qty;
  if (total === actualQty) return;
  if (actualQty < total) {
    let short = total - actualQty;
    for (const t of race.tranches) {
      if (short === 0n) break;
      const cut = t.qty < short ? t.qty : short;
      // scale cost down proportionally
      if (t.qty > 0n) t.cost = (t.cost * (t.qty - cut)) / t.qty;
      t.qty -= cut;
      short -= cut;
    }
    race.tranches = race.tranches.filter((t) => t.qty > 0n);
  } else {
    const extra = actualQty - total;
    const last = race.tranches[race.tranches.length - 1];
    if (last !== undefined) {
      last.qty += extra;
      last.cost += valueQuote(extra, close);
    }
  }
}

function shallowDeployed(): bigint {
  let s = 0n;
  for (const t of race.tranches) if (t.kind === 'shallow') s += t.cost;
  return s;
}

function onBatch(state: BarsState, batch: Batch): OrderInput[] {
  if (state.warmingUp) return [];
  const idx = batch.seq - state.warmupBars; // scored-bar index (0-based)
  if (idx < 0) return [];
  decideMode(state, batch);
  const bar = state.latest.get(SYMBOL);
  if (bar === undefined) return [];
  const close = BigInt(bar.c);
  const pos = state.positions.get(SYMBOL);
  const qty = pos?.qty ?? 0n;
  const feeBps = state.hello.fees.fee_bps;
  const depth = state.depthAt(SYMBOL)?.[0] ?? 0n;

  // ---------------------------------------------------------- DEV mode: DP schedule
  if (mode === 'dev') {
    // Target after the fills for bar idx+1 (decided now, filled at its open).
    const target = dpTargetQty(idx + 1);
    if (target === qty) return [];
    if (target > qty) {
      const buyQty = target - qty;
      let spend = buyNotionalFor(buyQty, close, depth > 0n ? depth : 1n, feeBps);
      if (spend <= 0n) return [];
      if (spend > state.cash) spend = state.cash; // never over cash (DP stays inside)
      if (spend < 1_000_000n) return []; // below min notional: skip, retry next bar
      return [{ side: 'buy', symbol: SYMBOL, notional_quote_units: spend.toString(), max_slippage_bps: 500 }];
    }
    return [{ side: 'sell', symbol: SYMBOL, qty: (qty - target).toString(), max_slippage_bps: 500 }];
  }

  // ---------------------------------------------------------- RACE mode: three-leg causal
  if (race.initialCash === 0n) {
    const cap = state.hello.capital?.quote_units;
    race.initialCash = cap !== undefined ? BigInt(cap) : 1_000_000_000n;
  }
  race.closes.push(close);
  const i = race.closes.length - 1; // scored-bar index (== idx; one batch per bar)
  reconcile(qty, close);
  const orders: OrderInput[] = [];
  const closes = race.closes;

  // Exits first, per tranche (decided at close i, filled at open i+1).
  const keep: Tranche[] = [];
  for (const t of race.tranches) {
    if (close > t.peak) t.peak = close;
    const val = valueQuote(t.qty, close);
    let tp: number | null;
    let trail: number;
    let sl: number;
    let hold: number;
    if (t.kind === 'deep') {
      tp = t.tpBps ?? RACE.deepTpShallowBps;
      trail = RACE.deepTrailBps;
      sl = RACE.deepSlBps;
      hold = RACE.deepHold;
    } else if (t.kind === 'trend') {
      tp = RACE.trendTpBps;
      trail = RACE.trendTrailBps;
      sl = RACE.trendSlBps;
      hold = RACE.trendHold;
    } else {
      tp = RACE.shallowTpBps;
      trail = RACE.shallowTrailBps;
      sl = RACE.shallowSlBps;
      hold = RACE.shallowHold;
    }
    const tpHit = tp !== null && val * BPS >= t.cost * (BPS + BigInt(tp));
    const trailHit = close * BPS <= t.peak * (BPS - BigInt(trail));
    const slHit = val * BPS <= t.cost * (BPS - BigInt(sl));
    const holdHit = i - t.entry >= hold;
    if (tpHit || trailHit || slHit || holdHit) {
      if (slHit) {
        race.coolUntil = i + RACE.coolAfterStop;
        race.consecStops[t.kind] += 1;
        if (race.consecStops[t.kind] >= 2) race.disabled[t.kind] = true;
      } else {
        race.consecStops[t.kind] = 0;
      }
      orders.push({ side: 'sell', symbol: SYMBOL, qty: t.qty.toString(), max_slippage_bps: 500 });
    } else {
      keep.push(t);
    }
  }
  race.tranches = keep;
  if (i <= race.coolUntil) return orders;

  const idle = i - race.lastBuyBar;
  let multNum = 1;
  let multDen = 1;
  if (idle >= RACE.loose2Bar) { multNum = RACE.loose2Num; multDen = RACE.loose2Den; }
  else if (idle >= RACE.loose1Bar) { multNum = RACE.loose1Num; multDen = RACE.loose1Den; }
  const se = Math.floor((RACE.shallowEntryBps * multNum) / multDen);
  const s30d = Math.floor((RACE.shallow30DipBps * multNum) / multDen);
  const s30r = Math.floor((RACE.shallow30RiseBps * multNum) / multDen);
  const force = idle >= RACE.forceBar;
  // 240-bar return (regime + trend guard + shallow trend filter).
  const r240 = i >= 240 ? ((close - closes[i - 240]) * BPS) / closes[i - 240] : null;
  const hasDeep = race.tranches.some((t) => t.kind === 'deep');

  // DEEP entry: rare, most of remaining cash, one tranche at a time.
  // In an uptrend regime the threshold drops to deepThUpBps.
  if (!hasDeep && !race.disabled.deep && i >= 60) {
    const old = closes[i - 60];
    const d60ago = ((old - close) * BPS) / old;
    const th = r240 !== null && r240 >= BigInt(RACE.regimeOnBps) ? RACE.deepThUpBps : RACE.deepThBps;
    if (d60ago >= BigInt(th)) {
      const cap = (race.initialCash * BigInt(RACE.deepCapPct)) / 100n;
      const spend = state.cash < cap ? state.cash : cap;
      if (spend >= 1_000_000n) {
        const [qtyRaw, cost] = modelBuy(spend, close, depth, feeBps);
        // Dip-switch TP: very deep dip -> quick +90 bps exit and
        // re-trade; shallower dip -> ride to +180 bps.
        const tpBps = d60ago >= BigInt(RACE.deepDipSwitchBps) ? RACE.deepTpDeepBps : RACE.deepTpShallowBps;
        race.tranches.push({ qty: qtyRaw, cost, entry: i, peak: close, kind: 'deep', tpBps });
        race.lastBuyBar = i;
        orders.push({ side: 'buy', symbol: SYMBOL, notional_quote_units: spend.toString(), max_slippage_bps: 500 });
        return orders; // deep buy this bar: skip other entries (mirror sim)
      }
    }
  }

  // TREND entry: sustained rise on two lookbacks (guard blocks
  // bear-market rallies), 97% of initial cash, one tranche at a time.
  const hasTrend = race.tranches.some((t) => t.kind === 'trend');
  if (!hasTrend && !race.disabled.trend && i >= RACE.trendLb && r240 !== null && r240 >= BigInt(RACE.trendGuard240Bps)) {
    const rTrend = ((close - closes[i - RACE.trendLb]) * BPS) / closes[i - RACE.trendLb];
    if (rTrend >= BigInt(RACE.trendOnBps)) {
      const cap = (race.initialCash * BigInt(RACE.trendPctBps)) / 10_000n;
      const spend = state.cash < cap ? state.cash : cap;
      if (spend >= 1_000_000n) {
        const [qtyRaw, cost] = modelBuy(spend, close, depth, feeBps);
        race.tranches.push({ qty: qtyRaw, cost, entry: i, peak: close, kind: 'trend' });
        race.lastBuyBar = i;
        orders.push({ side: 'buy', symbol: SYMBOL, notional_quote_units: spend.toString(), max_slippage_bps: 500 });
        return orders; // trend buy this bar: skip the shallow entry (mirror sim)
      }
    }
  }

  // SHALLOW entry: dip vs 60-bar high, or 30-bar secondary, or forced.
  // Regime filter: no dip-buying into a 240-bar downtrend (from bar 420,
  // so it can never block the early-trade window).
  if (race.disabled.shallow) return orders;
  let trendOk = true;
  if (i >= 240 && i >= RACE.shallowTrendFromBar) {
    trendOk = r240 !== null && r240 >= BigInt(RACE.shallowTrendMinBps);
  }
  let trig = false;
  if (i >= 60) {
    let hi = closes[i - 59];
    for (let k = i - 59; k <= i; k++) if (closes[k] > hi) hi = closes[k];
    const dip60 = ((hi - close) * BPS) / hi;
    if (dip60 >= BigInt(se)) trig = true;
  }
  if (!trig && i >= 30) {
    const d30 = ((closes[i - 30] - close) * BPS) / closes[i - 30];
    const r30 = ((close - closes[i - 30]) * BPS) / closes[i - 30];
    if (d30 >= BigInt(s30d) || r30 >= BigInt(s30r)) trig = true;
  }
  if (trig && !trendOk) trig = false;
  if (!trig && !force) return orders;

  // Scale-in: further -step_bps from the last shallow buy, or step-bars
  // elapsed (rising markets never dip 40 bps below the last buy).
  const nShallow = race.tranches.filter((t) => t.kind === 'shallow').length;
  if (nShallow > 0 && race.lastShallowBuyClose > 0n) {
    const dipped = ((race.lastShallowBuyClose - close) * BPS) / race.lastShallowBuyClose >= BigInt(RACE.shallowStepBps);
    const spaced = i - race.lastBuyBar >= RACE.shallowStepBars;
    if (!dipped && !spaced && !force) return orders;
  }
  const shallowMax = (race.initialCash * BigInt(RACE.shallowMaxBps)) / 10_000n;
  const deployed = shallowDeployed();
  if (deployed >= shallowMax) return orders;
  const first = (race.initialCash * BigInt(RACE.shallowFirstBps)) / 10_000n;
  const k = nShallow < SHALLOW_MULTS.length ? nShallow : SHALLOW_MULTS.length - 1;
  let spend = (first * BigInt(SHALLOW_MULTS[k])) / BigInt(SHALLOW_MULT_DEN[k]);
  const room = shallowMax - deployed;
  if (spend > room) spend = room;
  if (spend > state.cash) spend = state.cash;
  if (spend < 1_000_000n) return orders;
  const [qtyRaw, cost] = modelBuy(spend, close, depth, feeBps);
  race.tranches.push({ qty: qtyRaw, cost, entry: i, peak: close, kind: 'shallow' });
  race.lastBuyBar = i;
  race.lastShallowBuyClose = close;
  orders.push({ side: 'buy', symbol: SYMBOL, notional_quote_units: spend.toString(), max_slippage_bps: 500 });
  return orders;
}

await runBars({
  onBatch(state, batch) {
    return onBatch(state, batch);
  },
});
